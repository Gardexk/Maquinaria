    private void registrartxtMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_registrartxtMouseClicked
        
        Maquina maquina = new Maquina();
        Ctrl_Maquina controlmaquina = new Ctrl_Maquina();
        
        String tipomaquina="";
        String fecha="";
        String estatus="Disponible";
        
        java.util.Date date = new java.util.Date();
        SimpleDateFormat f = new SimpleDateFormat("yyyy-MM-dd");
        
        tipomaquina=combotipo.getSelectedItem().toString().trim();
        fecha = f.format(txt_fecha.getDate());
        
        //System.out.println("La fecha que puse es " + fecha);
        
        
        if(txt_id.getText().equals("")|| txt_marca.getText().equals("")|| txt_modelo.getText().equals("")|| txt_precio.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Complete todos los campos");
        }else{
            
            if(!controlmaquina.existeMaquina(txt_id.getText().trim())){
                
                if(tipomaquina.equalsIgnoreCase("Selecciona el tipo de maquina")){
                    JOptionPane.showMessageDialog(null, "Selecciona el tipo de maquina");   
                }else{
                    try {
                        maquina.setIdMaquina(Integer.parseInt(txt_id.getText().trim()));
                        maquina.setMarca(txt_marca.getText().trim());
                        maquina.setModelo(Integer.parseInt(txt_modelo.getText().trim()));
                        
                        if (tipomaquina.equalsIgnoreCase("Bulldozer")) {
                            maquina.setTipoMaquina("Bulldozer");
                        } else if (tipomaquina.equalsIgnoreCase("Excavadora")) {
                            maquina.setTipoMaquina("Excavadora");
                        } else if (tipomaquina.equalsIgnoreCase("Miniexcavadora")) {
                            maquina.setTipoMaquina("Miniexcavadora");
                        } else if (tipomaquina.equalsIgnoreCase("Retroexcavadora")) {
                            maquina.setTipoMaquina("Retroexcavadora");
                        } else if (tipomaquina.equalsIgnoreCase("Minicargador")) {
                            maquina.setTipoMaquina("Minicargador");
                        } else if (tipomaquina.equalsIgnoreCase("Motoniveladoras")) {
                            maquina.setTipoMaquina("Motoniveladoras");
                        } else if (tipomaquina.equalsIgnoreCase("Camiones articulados")) {
                            maquina.setTipoMaquina("Camiones articulados");
                        } 
                        
                        maquina.setFechaAdquisicion(java.sql.Date.valueOf(fecha));
                        maquina.setEstatus(estatus);

                        String precioTXT = "";
                        double Precio = 0.0;
                        precioTXT = txt_precio.getText().trim();
                        boolean aux = false;
                        /*
                            *si el usuario ingresa coma como punto decimal lo trasformamos a punto
                         */
                        for (int i = 0; i < precioTXT.length(); i++) {
                            if (precioTXT.charAt(i) == ',') {
                                String precioNuevo = precioTXT.replace(",", ".");
                                Precio = Double.parseDouble(precioNuevo);
                                aux = true;
                            }
                        }

                        // evaluamos la condicion
                        if (aux == true) {
                            maquina.setCostoRenta(Precio);
                        } else {
                            Precio = Double.parseDouble(precioTXT);
                            maquina.setCostoRenta(Precio);
                        }

                        if (controlmaquina.guardar(maquina)) {
                            JOptionPane.showMessageDialog(null, "Registro Guardado");

                        } else {
                            JOptionPane.showMessageDialog(null, "Error al guardar");
                        }

                    } catch (HeadlessException | NumberFormatException e) {
                        System.out.println("Error en: " + e);
                    }

                }
                
                
            }else{
                JOptionPane.showMessageDialog(null, "La maquina ya existe");
            }
        }
        
    }//GEN-LAST:event_registrartxtMouseClicked

    private void txt_idKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_idKeyTyped
        // Obtener el carácter ingresado por el usuario
    char c = evt.getKeyChar();
    
    // Obtener el texto actual del campo de ID
    String id = txt_id.getText();
    
    // Verificar que el carácter sea un dígito numérico y que la longitud actual del ID sea menor o igual a 9
    if (Character.isDigit(c) && id.length() < 10) {
        // Si se cumple, permitir el carácter ingresado en el campo
    } else {
        // Si no se cumple, consumir el carácter para evitar que se ingrese en el campo
        evt.consume();
    }
    }//GEN-LAST:event_txt_idKeyTyped

