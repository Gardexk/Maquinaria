    private void txt_precioKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_precioKeyTyped
   
    // Obtener el carácter ingresado por el usuario
    char c = evt.getKeyChar();
    
    // Obtener el texto actual del campo de precio
    String precio = txt_precio.getText();
    
    // Verificar que el carácter sea un dígito numérico, un punto o una coma, y que la longitud actual del precio sea menor o igual a 9 (7 dígitos antes del separador y 2 después)
    if ((Character.isDigit(c) || c == '.' || c == ',') && precio.length() <= 30) {
        // Si se cumple, permitir el carácter ingresado en el campo
        if (precio.indexOf('.') == -1 && precio.indexOf(',') == -1) {
            // El separador decimal no se ha ingresado aún, permitir cualquier carácter
        } else if (precio.indexOf('.') != -1) {
            // El separador decimal es un punto
            int separador = precio.indexOf('.');
            if (precio.length() - separador <= 2) {
                // Solo se han ingresado 1 o 2 dígitos después del punto, permitir el carácter ingresado en el campo
            } else {
                evt.consume();
            }
        } else if (precio.indexOf(',') != -1) {
            // El separador decimal es una coma
            int separador = precio.indexOf(',');
            if (precio.length() - separador <= 2) {
                // Solo se han ingresado 1 o 2 dígitos después de la coma, permitir el carácter ingresado en el campo
            } else {
                evt.consume();
            }
        }
    } else {
        // Si no se cumple, consumir el carácter para evitar que se ingrese en el campo
        evt.consume();
    }
    }//GEN-LAST:event_txt_precioKeyTyped


