    private void CargarCombocliente() {
    Connection cn = conexion.Conexion.conectar();
    String sql = "select * from clientes order by nombre asc";
    Statement st;

    try {

        st = cn.createStatement();
        ResultSet rs = st.executeQuery(sql);
        ComboBox_cliente.removeAllItems();
        ComboBox_cliente.addItem("Selecciona al Cliente");
        while (rs.next()) {
            String nombre = rs.getString("nombre");
            ComboBox_cliente.addItem(nombre);
        }
        
        cn.close();
    } catch (SQLException e) {
        System.out.println("Error al cargar el cliente");
    }
    
    ComboBox_cliente.addActionListener(new ActionListener() {
        @Override
        public void actionPerformed(ActionEvent e) {
            if (ComboBox_cliente.getSelectedIndex() > 0) {
                String nombre_cliente = ComboBox_cliente.getSelectedItem().toString();
                
                EnviarDatosClienteSeleccionado(nombre_cliente);
            }
        }
    });
}

private void EnviarDatosClienteSeleccionado(String nombre_cliente) {
    try {
        Connection con = conexion.Conexion.conectar();
        PreparedStatement pst = con.prepareStatement(
                "select * from clientes where nombre = ?");
        pst.setString(1, nombre_cliente);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            id_cliente = Integer.parseInt(rs.getString("id_cliente"));
            txt_nombrecliente.setText(rs.getString("nombre"));
            this.txt_direccioncliente.setText(rs.getString("direccion"));
            txt_emailcliente.setText(rs.getString("email"));
            txt_telefonocliente.setText(rs.getString("telefono"));
            
        }
        con.close();

    } catch (SQLException e) {
        System.out.println("Error al seleccionar al cliente" + e);
    }
}

