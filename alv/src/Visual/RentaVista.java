    private void Boton_rentaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_Boton_rentaMouseClicked
        // TODO add your handling code here:
        
        Renta renta = new Renta();
        Ctrl_Renta ctrl_Renta = new Ctrl_Renta();
        
        String fecha1;
        String fecha2;
        java.util.Date date = new java.util.Date();
        SimpleDateFormat f = new SimpleDateFormat("yyyy-MM-dd");
       
        
        if(txt_fecha_termino.getDate() == null){
            JOptionPane.showMessageDialog(null, "Completa todos los campos");
        }else{
            fecha1 = f.format(txt_fecha_entrega.getDate());
            fecha2 = f.format(txt_fecha_termino.getDate());

            Date fechaInicio = txt_fecha_entrega.getDate();
            Date fechaFin = txt_fecha_termino.getDate();

            long diff = fechaFin.getTime() - fechaInicio.getTime();
            long diffDays = diff / (24 * 60 * 60 * 1000);

            rentaTotal = rentamaquina * (diffDays +1 );
            txt_RentaTotal.setText(String.valueOf(rentaTotal));
            
            try {
                renta.setCostoTotal(rentaTotal);
                renta.setIdCliente(id_cliente);
                renta.setIdOperario(id_operador);
                renta.setFechaInicio(java.sql.Date.valueOf(fecha1));
                renta.setFechaFin(java.sql.Date.valueOf(fecha2));
                renta.setIdMaquinaria(id_maquina);
                
                if(!ctrl_Renta.guardar(renta)){
                    JOptionPane.showMessageDialog(null, "Se realizo la renta");
                    Limpiar();
                    
                }else{
                    JOptionPane.showMessageDialog(null, "No se realizo la renta");
                }
                
            } catch (HeadlessException | NumberFormatException e) {
            }
            
            
        }
        
        
        
    }//GEN-LAST:event_Boton_rentaMouseClicked

